// @vitest-environment node
import postcss from 'postcss'
import tailwindcss from 'tailwindcss'
import { describe, expect, it } from 'vitest'
import config from '../../tailwind.config'
import { GRADIENT_BAND_COLOURS, GRADIENT_PRESETS, getBandColourForProject, getGradientForProject } from '../gradient-utils'

describe('project card gradients', () => {
  it('are generated by Tailwind, not purged', async () => {
    // Tailwind only emits classes it finds in `content`; a preset it never
    // sees renders as no background at all, which is a plain grey card.
    const { css } = await postcss([tailwindcss(config)]).process('@tailwind utilities;', {
      from: undefined,
    })
    const classes = GRADIENT_PRESETS.flatMap((preset) => preset.split(' '))
    const missing = classes.filter((cls) => !css.includes(`.${cls} {`))
    expect(missing).toEqual([])
  })

  it('picks the same preset for the same project', () => {
    const id = '7c9e6679-7425-40de-944b-e07fc1f90ae7'
    expect(getGradientForProject(id)).toBe(getGradientForProject(id))
    expect(GRADIENT_PRESETS).toContain(getGradientForProject(id))
  })
})

describe('project card band colours', () => {
  it('has one for every gradient, dark enough for white text', () => {
    expect(GRADIENT_BAND_COLOURS).toHaveLength(GRADIENT_PRESETS.length)
    for (const colour of GRADIENT_BAND_COLOURS) {
      expect(colour).toMatch(/^#[0-9a-f]{6}$/)
      const [r, g, b] = [1, 3, 5].map((at) => {
        const v = parseInt(colour.slice(at, at + 2), 16) / 255
        return v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4
      })
      // Contrast with white of at least 4.5:1 (WCAG AA for small text).
      expect(1.05 / (0.2126 * r + 0.7152 * g + 0.0722 * b + 0.05)).toBeGreaterThanOrEqual(4.5)
    }
  })

  it('goes with the gradient the project gets', () => {
    for (const id of ['a', 'b', 'c', 'p1', '7c9e6679-7425-40de-944b-e07fc1f90ae7']) {
      const at = GRADIENT_PRESETS.indexOf(getGradientForProject(id))
      expect(getBandColourForProject(id)).toBe(GRADIENT_BAND_COLOURS[at])
    }
  })
})
